<#
.SYNOPSIS
Generate Go and C# from one schema configuration using locked official tools.
.EXAMPLE
pwsh ./tools/Generate-Protocol.ps1 -Config ./examples/protobuf/protocol.json -Check
#>
[CmdletBinding()]
param([Parameter(Mandatory)][string]$Config, [switch]$Check)
$ErrorActionPreference = 'Stop'
. "$PSScriptRoot/internal/Protobuf.ps1"
$configPath = (Resolve-Path -LiteralPath $Config).Path
$base = Split-Path -Parent $configPath
$settings = Get-Content -LiteralPath $configPath -Raw | ConvertFrom-Json
foreach ($key in @('schemaRoot','inputs','goOutput','csharpOutput')) {
    if (-not $settings.$key) { throw "Missing configuration property: $key" }
}
function Resolve-ConfigPath([string]$Path) {
    if ([IO.Path]::IsPathRooted($Path)) { return [IO.Path]::GetFullPath($Path) }
    return [IO.Path]::GetFullPath((Join-Path $base $Path))
}
$schemaRoot = Resolve-ConfigPath $settings.schemaRoot
if (-not (Test-Path -LiteralPath $schemaRoot -PathType Container)) { throw "Schema root does not exist: $schemaRoot" }
if ($settings.inputs -is [string]) { throw 'inputs must be a JSON array of relative .proto paths.' }
foreach ($inputPath in $settings.inputs) {
    if ($inputPath -isnot [string] -or [IO.Path]::IsPathRooted($inputPath) -or $inputPath.StartsWith('-') -or $inputPath -notmatch '\.proto$') {
        throw "Expected a relative .proto input path: $inputPath"
    }
    $fullInput = [IO.Path]::GetFullPath((Join-Path $schemaRoot $inputPath))
    if (-not $fullInput.StartsWith($schemaRoot.TrimEnd('/','\') + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or -not (Test-Path -LiteralPath $fullInput -PathType Leaf)) {
        throw "Input must exist within schemaRoot: $inputPath"
    }
}
$goDestination = Resolve-ConfigPath $settings.goOutput
$csDestination = Resolve-ConfigPath $settings.csharpOutput
foreach ($destination in @($goDestination, $csDestination)) {
    if ($destination -eq [IO.Path]::GetPathRoot($destination) -or $destination -eq $base -or
        $schemaRoot.StartsWith($destination.TrimEnd('/','\') + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or
        $destination.StartsWith($schemaRoot.TrimEnd('/','\') + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase) -or $destination -eq $schemaRoot) {
        throw "Output must be a dedicated directory outside the schema root and not its ancestor: $destination"
    }
}
if ($goDestination -eq $csDestination) { throw 'Go and C# outputs must use different directories.' }
$protoc = Resolve-ProtobufCompiler
$plugin = Resolve-ProtobufGoPlugin
$temporary = Join-Path $script:ProtobufCache ([Guid]::NewGuid().ToString('N'))
try {
    $goTemp = Join-Path $temporary 'go'
    $csTemp = Join-Path $temporary 'csharp'
    New-Item -ItemType Directory -Force $goTemp,$csTemp | Out-Null
    & $protoc "--proto_path=$schemaRoot" "--plugin=protoc-gen-go=$plugin" "--go_out=$goTemp" '--go_opt=paths=source_relative' "--csharp_out=$csTemp" @($settings.inputs)
    if ($LASTEXITCODE -ne 0) { throw 'Official protoc generation failed.' }
    foreach ($output in @(@($goTemp, $goDestination, '*.pb.go'), @($csTemp, $csDestination, '*.cs'))) {
        $destination = $output[1]
        foreach ($file in Get-ChildItem -LiteralPath $output[0] -Recurse -File) {
            $relative = [IO.Path]::GetRelativePath($output[0], $file.FullName)
            $target = Join-Path $destination $relative
            if ($Check) {
                if (-not (Test-Path -LiteralPath $target) -or (Get-FileHash -LiteralPath $target).Hash -ne (Get-FileHash -LiteralPath $file.FullName).Hash) { throw "Generated file is stale or missing: $target" }
            } else {
                if (Test-Path -LiteralPath $target) {
                    $existingHeader = (Get-Content -LiteralPath $target -TotalCount 8) -join "`n"
                    if ($existingHeader -notmatch '(Generated by the protocol buffer compiler|Code generated by protoc-gen-go)') {
                        throw "Refusing to overwrite a file without an official generated header: $target"
                    }
                }
                New-Item -ItemType Directory -Force (Split-Path -Parent $target) | Out-Null
                Copy-Item -LiteralPath $file.FullName -Destination $target -Force
            }
        }
        # Detect removed/renamed schema output without deleting user code or Unity metadata.
        if (Test-Path -LiteralPath $destination) {
            foreach ($existing in Get-ChildItem -LiteralPath $destination -Recurse -File -Filter $output[2]) {
                $header = Get-Content -LiteralPath $existing.FullName -TotalCount 8
                if (($header -join "`n") -notmatch '(Generated by the protocol buffer compiler|Code generated by protoc-gen-go)') { continue }
                $relative = [IO.Path]::GetRelativePath($destination, $existing.FullName)
                if (-not (Test-Path -LiteralPath (Join-Path $output[0] $relative))) {
                    throw "Obsolete generated file: $($existing.FullName). Remove it explicitly after checking references; .meta files are never deleted."
                }
            }
        }
    }
    Write-Host $(if ($Check) { 'Protocol generated files are current.' } else { 'Generated Go and C# protocol files.' })
} finally {
    # Only the unique directory created above can be removed.
    if (Test-Path -LiteralPath $temporary) {
        $resolvedTemporary = (Resolve-Path -LiteralPath $temporary).Path
        $expectedParent = [IO.Path]::GetFullPath($script:ProtobufCache)
        if ((Split-Path -Parent $resolvedTemporary) -ne $expectedParent -or (Split-Path -Leaf $resolvedTemporary) -notmatch '^[a-f0-9]{32}$') {
            throw "Refusing to remove unexpected generation path: $resolvedTemporary"
        }
        Remove-Item -LiteralPath $resolvedTemporary -Recurse -Force
    }
}
